def diff_budget(context_tokens: int) -> int:
    """How many tokens of diff fit in one model call, after the room kept for the rest."""
    return context_tokens - INSTRUCTIONS_TOKENS - EXPLORED_TOKENS - ANSWER_TOKENS


def select_files(
    pull_request: PullRequest,
    *,
    context_tokens: int,
    ignore: tuple[str, ...] = (),
) -> ReviewScope:
    """Skip what shouldn't or can't be reviewed, rank the rest, and pack it into batches.

    `ignore` holds the rules file's ignore patterns (FR-17).
    """
    budget = diff_budget(context_tokens)
    skipped: list[SkippedFile] = []
    candidates: list[tuple[ChangedFile, int]] = []
    for file in pull_request.files:
        reason = _skip_reason(file, ignore)
        tokens = estimate_tokens(render_file(file)) if reason is None else 0
        if reason is None and tokens > budget:
            reason = SkipReason.TOO_LARGE
        if reason is None:
            candidates.append((file, tokens))
        else:
            skipped.append(SkippedFile(path=file.path, reason=reason))

    candidates.sort(key=lambda item: _rank(item[0], item[1], pull_request.languages))
    batches: list[list[ChangedFile]] = []
    used = budget  # forces a new batch for the first file
    for file, tokens in candidates:
        if used + tokens > budget:
            batches.append([])
            used = 0
        batches[-1].append(file)
        used += tokens
    return ReviewScope(batches=tuple(tuple(batch) for batch in batches), skipped=tuple(skipped))


def _skip_reason(file: ChangedFile, ignore: tuple[str, ...]) -> SkipReason | None:
    """Why `file` is skipped before its size is even considered, or None to keep it."""
    path = PurePosixPath(file.path)
    if globs.matches_any(file.path, ignore):
        return SkipReason.IGNORED_BY_RULES
    if path.name in LOCK_FILES or path.suffix == ".lock":
        return SkipReason.LOCK_FILE
    if path.suffix.lower().lstrip(".") in BINARY_EXTENSIONS:
        return SkipReason.BINARY
    if globs.matches_any(file.path, GENERATED_PATTERNS) or _has_generated_marker(file):
        return SkipReason.GENERATED
    if not file.diff_available:
        # GitHub leaves the diff out of binary files and of very large diffs. A binary
        # file with an unknown extension is counted as too large, which leaves a gap:
        # that's the safe side, because the summary then asks for a person to look.
        return SkipReason.TOO_LARGE
    return None


def _has_generated_marker(file: ChangedFile) -> bool:
    """True when one of the first added lines carries a code generator's marker."""
    added = [line.text.lower() for line in file.lines if line.kind is LineKind.ADDED]
    return any(marker in text for text in added[:_MARKER_LINES] for marker in GENERATED_MARKERS)


def _rank(file: ChangedFile, tokens: int, languages: tuple[str, ...]) -> tuple[int, int, int]:
    """Sort key: kind of file, then the repository's most used language, then size."""
    language = LANGUAGE_OF_EXTENSION.get(PurePosixPath(file.path).suffix.lower().lstrip("."))
    language_rank = languages.index(language) if language in languages else len(languages)
    return (_group(file.path), language_rank, tokens)


def _group(path_text: str) -> int:
    path = PurePosixPath(path_text)
    folders = {part.lower() for part in path.parts[:-1]}
    if folders & _TEST_FOLDERS or any(path.match(name) for name in _TEST_NAMES):
        return _TESTS
    if (
        path.name in _DOCS_AND_CONFIG_NAMES
        or path.suffix.lower().lstrip(".") in _DOCS_AND_CONFIG_EXTENSIONS
        or "docs" in folders
    ):
        return _DOCS_AND_CONFIG
    return _SOURCE
