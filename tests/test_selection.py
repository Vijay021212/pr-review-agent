"""Tests for file selection: skips with reasons, ranking and batching (FR-3, FR-4)."""

from __future__ import annotations

import pytest

from pr_review_agent.diff_text import estimate_tokens, render_file
from pr_review_agent.domain import ChangedFile, ReviewScope, SkipReason
from pr_review_agent.selection import diff_budget, select_files
from tests.builders import make_file, make_pull_request

# A small context window keeps the budget small: 7000 - 2500 - 3000 - 1024 = 476 tokens.
SMALL_CONTEXT = 7000


def select(*files: ChangedFile, context: int = 16384, **options: object) -> ReviewScope:
    pull_request = make_pull_request(files=files, **options.pop("pr", {}))  # type: ignore[arg-type]
    return select_files(pull_request, context_tokens=context, **options)  # type: ignore[arg-type]


def skip_reason(file: ChangedFile, ignore: tuple[str, ...] = ()) -> SkipReason | None:
    scope = select(file, ignore=ignore)
    return scope.skipped[0].reason if scope.skipped else None


def sized(path: str, lines: int) -> ChangedFile:
    return make_file(path, [f"value_{n} = {n}" for n in range(lines)])


def test_the_budget_leaves_room_for_everything_but_the_diff() -> None:
    assert diff_budget(16384) == 16384 - 2500 - 3000 - 1024
    assert diff_budget(SMALL_CONTEXT) == 476


@pytest.mark.parametrize(
    "path",
    ["uv.lock", "web/package-lock.json", "Cargo.lock", "deps/custom.lock", "go.sum", "yarn.lock"],
)
def test_lock_files_are_skipped(path: str) -> None:
    assert skip_reason(make_file(path)) is SkipReason.LOCK_FILE


@pytest.mark.parametrize(
    "path", ["assets/logo.png", "docs/spec.PDF", "lib/native.so", "models/net.onnx"]
)
def test_binary_files_are_skipped(path: str) -> None:
    assert skip_reason(make_file(path, (), diff_available=False)) is SkipReason.BINARY


@pytest.mark.parametrize(
    "path",
    [
        "proto/api_pb2.py",
        "dist/app.js",
        "web/node_modules/left-pad/index.js",
        "static/app.min.js",
        "src/__generated__/schema.ts",
        "client/types.generated.ts",
    ],
)
def test_generated_files_are_skipped_by_name(path: str) -> None:
    assert skip_reason(make_file(path)) is SkipReason.GENERATED


@pytest.mark.parametrize(
    "first_line",
    [
        "# @generated by protoc-gen-python",
        "// Code generated by mockgen. DO NOT EDIT.",
        "# This file is auto-generated, do not edit",
    ],
)
def test_generated_files_are_skipped_by_their_marker(first_line: str) -> None:
    assert skip_reason(make_file("src/models.py", [first_line, "x = 1"])) is SkipReason.GENERATED


def test_a_marker_far_down_the_file_doesnt_count() -> None:
    lines = [f"x{n} = {n}" for n in range(5)] + ["# do not edit this line by hand"]
    assert skip_reason(make_file("src/app.py", lines)) is None


def test_files_matching_the_rules_file_are_skipped() -> None:
    ignore = ("tests/fixtures/**", "*.snap")
    assert skip_reason(make_file("tests/fixtures/data.py"), ignore) is SkipReason.IGNORED_BY_RULES
    assert skip_reason(make_file("ui/button.snap"), ignore) is SkipReason.IGNORED_BY_RULES
    # The rules file wins over every other reason.
    assert skip_reason(make_file("deps/x.lock"), ("deps/**",)) is SkipReason.IGNORED_BY_RULES


def test_a_missing_diff_of_an_unknown_kind_is_a_gap() -> None:
    reason = skip_reason(make_file("src/huge.py", (), diff_available=False))
    assert reason is SkipReason.TOO_LARGE
    assert reason.is_gap


@pytest.mark.parametrize(
    "path",
    [
        "src/app.py",
        "README.md",
        "tests/test_app.py",
        "src/lockpick.py",  # contains "lock", but isn't a lock file
        "build_tools.py",  # starts with "build", but isn't in a build/ folder
        "src/build/steps.py",  # a source folder named "build", below the root
        "src/binary.py",
        "Dockerfile",
    ],
)
def test_ordinary_files_are_reviewed(path: str) -> None:
    scope = select(make_file(path))
    assert scope.skipped == ()
    assert [file.path for file in scope.files] == [path]


def test_a_file_bigger_than_the_budget_is_too_large_and_a_gap() -> None:
    scope = select(sized("src/small.py", 3), sized("src/big.py", 200), context=SMALL_CONTEXT)
    assert [file.path for file in scope.files] == ["src/small.py"]
    assert [(skip.path, skip.reason) for skip in scope.skipped] == [
        ("src/big.py", SkipReason.TOO_LARGE)
    ]
    assert scope.has_gaps


def test_source_comes_before_tests_and_tests_before_docs_and_config() -> None:
    files = [
        make_file("README.md"),
        make_file("tests/test_cart.py"),
        make_file("pyproject.toml"),
        make_file("src/cart.py"),
        make_file("docs/guide.py"),
        make_file("src/cart_test.go"),
        make_file("conftest.py"),
    ]
    order = [file.path for file in select(*files, pr={"languages": ("Python",)}).files]
    assert order[0] == "src/cart.py"
    assert set(order[1:4]) == {"tests/test_cart.py", "src/cart_test.go", "conftest.py"}
    assert set(order[4:]) == {"README.md", "pyproject.toml", "docs/guide.py"}


def test_the_repositorys_most_used_language_comes_first() -> None:
    files = [make_file("tool.go"), make_file("web/app.ts"), make_file("src/app.py")]
    scope = select(*files, pr={"languages": ("Python", "TypeScript")})
    assert [file.path for file in scope.files] == ["src/app.py", "web/app.ts", "tool.go"]


def test_smaller_diffs_come_first_within_a_group_and_language() -> None:
    scope = select(sized("src/large.py", 30), sized("src/small.py", 2), sized("src/mid.py", 10))
    assert [file.path for file in scope.files] == ["src/small.py", "src/mid.py", "src/large.py"]


def test_batches_fill_up_to_the_budget_and_never_past_it() -> None:
    files = [sized(f"src/f{n:02}.py", 6 + n) for n in range(12)]
    scope = select(*files, context=SMALL_CONTEXT)
    budget = diff_budget(SMALL_CONTEXT)
    assert len(scope.batches) > 1
    for batch in scope.batches:
        assert sum(estimate_tokens(render_file(file)) for file in batch) <= budget
    # Ranked order is kept across batches.
    sizes = [estimate_tokens(render_file(file)) for file in scope.files]
    assert sizes == sorted(sizes)


def test_a_file_exactly_the_budget_fills_a_batch_alone() -> None:
    budget = diff_budget(SMALL_CONTEXT)
    # Grow a file until its rendered diff is exactly the budget.
    text = "x"
    file = make_file("src/exact.py", [text])
    while estimate_tokens(render_file(file)) < budget:
        text += "x"
        file = make_file("src/exact.py", [text])
    assert estimate_tokens(render_file(file)) == budget
    scope = select(file, sized("src/tiny.py", 1), context=SMALL_CONTEXT)
    assert [len(batch) for batch in scope.batches] == [1, 1]


def test_every_changed_file_is_either_reviewed_or_listed_as_skipped() -> None:
    files = [
        make_file("uv.lock"),
        make_file("logo.png", (), diff_available=False),
        make_file("dist/app.js"),
        make_file("tests/fixtures/x.py"),
        sized("src/big.py", 200),
        *(sized(f"src/m{n}.py", 5) for n in range(8)),
    ]
    scope = select(*files, context=SMALL_CONTEXT, ignore=("tests/fixtures/**",))
    reviewed = [file.path for file in scope.files]
    skipped = [skip.path for skip in scope.skipped]
    assert sorted(reviewed + skipped) == sorted(file.path for file in files)
    assert not set(reviewed) & set(skipped)
    assert {skip.reason for skip in scope.skipped} == {
        SkipReason.LOCK_FILE,
        SkipReason.BINARY,
        SkipReason.GENERATED,
        SkipReason.IGNORED_BY_RULES,
        SkipReason.TOO_LARGE,
    }


def test_a_pull_request_without_files_has_nothing_to_review() -> None:
    scope = select()
    assert scope.batches == ()
    assert scope.skipped == ()
